namespace CanonBridge;

/// <summary>
/// Fake camera backend used when running with --mock / CANON_BRIDGE_MOCK=1.
/// Lets the HTTP contract be exercised end-to-end without EDSDK.dll or a
/// physical camera attached. Mirrors backend/internal/camera/mock.go on the
/// Go side (same "tiny 1x1 JPEG" trick).
/// </summary>
public sealed class MockCameraSession : ICameraSession
{
    // Smallest possible valid JPEG (1x1 black pixel).
    private static readonly byte[] TinyJpeg =
    {
        0xFF, 0xD8, 0xFF, 0xDB, 0x00, 0x43, 0x00, 0x03, 0x02, 0x02, 0x02, 0x02,
        0x02, 0x03, 0x02, 0x02, 0x02, 0x03, 0x03, 0x03, 0x03, 0x04, 0x06, 0x04,
        0x04, 0x04, 0x04, 0x04, 0x08, 0x06, 0x06, 0x05, 0x06, 0x09, 0x08, 0x0A,
        0x0A, 0x09, 0x08, 0x09, 0x09, 0x0A, 0x0C, 0x0F, 0x0C, 0x0A, 0x0B, 0x0E,
        0x0B, 0x09, 0x09, 0x0D, 0x11, 0x0D, 0x0E, 0x0F, 0x10, 0x10, 0x11, 0x10,
        0x0A, 0x0C, 0x12, 0x13, 0x12, 0x10, 0x13, 0x0F, 0x10, 0x10, 0x10, 0xFF,
        0xC9, 0x00, 0x0B, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
        0xFF, 0xCC, 0x00, 0x06, 0x00, 0x10, 0x10, 0x05, 0xFF, 0xDA, 0x00, 0x08,
        0x01, 0x01, 0x00, 0x00, 0x3F, 0x00, 0xD2, 0xCF, 0x20, 0xFF, 0xD9,
    };

    private readonly string _capturesDir;

    public MockCameraSession(string capturesDir)
    {
        _capturesDir = capturesDir;
        Directory.CreateDirectory(_capturesDir);
    }

    public IReadOnlyList<(string Model, string Port)> ListCameras() =>
        new[] { ("Mock Canon EOS", "mock:0001") };

    public (bool Success, string? FilePath, string? Error) Capture(string? port)
    {
        Thread.Sleep(300); // simulate shutter latency
        var path = Path.Combine(_capturesDir, $"{DateTimeOffset.UtcNow:yyyyMMdd-HHmmss-fff}.jpg");
        File.WriteAllBytes(path, TinyJpeg);
        return (true, path, null);
    }

    public (byte[]? Jpeg, string? Error) GetLiveViewFrame() => (TinyJpeg, null);

    public void Dispose() { }
}
